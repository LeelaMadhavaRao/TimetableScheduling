// Generates scripts/022_sample_college_hierarchy.sql from experiments/dataset.ts so the
// database seed and the offline experiment always describe the same college.
//
//   npm run experiment:sql

import { writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { SRKR_DATASET } from "./dataset.ts"
import { loadKaggleDataset } from "./kaggle-dataset.ts"

const DATA = process.env.DATASET === "kaggle" ? loadKaggleDataset() : SRKR_DATASET
const { college: COLLEGE, departmentAdminPassword: DEPARTMENT_ADMIN_PASSWORD, departments: DEPARTMENTS, faculty: FACULTY, rooms: ROOMS, sections: SECTIONS, subjects: SUBJECTS } = DATA
const OUTPUT = DATA.key === "kaggle" ? "023_kaggle_derived_college.sql" : "022_sample_college_hierarchy.sql"

const q = (v: string) => `'${v.replace(/'/g, "''")}'`
const C = q(COLLEGE.id)
const dept = (code: string) => `(SELECT id FROM departments WHERE college_id = ${C} AND code = ${q(code)})`
const faculty = (code: string) => `(SELECT id FROM faculty WHERE code = ${q(code)})`
const subject = (code: string) => `(SELECT id FROM subjects WHERE college_id = ${C} AND code = ${q(code)})`
const section = (name: string) => `(SELECT id FROM sections WHERE college_id = ${C} AND name = ${q(name)})`

const out: string[] = []
const push = (...lines: string[]) => out.push(...lines)

push(
  "-- =============================================",
  `-- ${OUTPUT.slice(0, 3)}: ${DATA.title}`,
  `-- GENERATED by "${DATA.key === "kaggle" ? "DATASET=kaggle " : ""}npm run experiment:sql" - edit the dataset source, not this file.`,
  ...(DATA.notes || []).map((n) => `--   ${n}`),
  "-- Run AFTER 000_complete_setup.sql and 021_college_department_hierarchy.sql.",
  "-- Re-running replaces only this sample college (deleting the college cascades to its data).",
  "--",
  `-- College admin   : ${COLLEGE.username} / ${COLLEGE.password}`,
  `-- Department admins: ${DEPARTMENTS.map((d) => d.admin).join(", ")} / ${DEPARTMENT_ADMIN_PASSWORD}`,
  `-- Faculty login   : faculty code + phone, e.g. ${FACULTY[0].code} / ${FACULTY[0].phone}`,
  "-- =============================================",
  "",
  "BEGIN;",
  "",
  `DELETE FROM user_sessions WHERE user_id IN (SELECT id FROM department_admins WHERE college_id = ${C}) OR user_id = ${C};`,
  `DELETE FROM timetable_administrators WHERE id = ${C} OR username = ${q(COLLEGE.username)};`,
  "",
  "-- College administrator (created by the default system admin)",
  "INSERT INTO timetable_administrators (id, username, password_hash, name, email, institution_name, is_active, created_by)",
  `VALUES (${C}, ${q(COLLEGE.username)}, hash_password(${q(COLLEGE.password)}), ${q(COLLEGE.name)}, ${q(COLLEGE.email)}, ${q(COLLEGE.institution)}, true,`,
  "        (SELECT id FROM admin_users WHERE username = 'admin'));",
  "",
  "-- Departments",
  "INSERT INTO departments (name, code, college_id, created_by) VALUES",
  DEPARTMENTS.map((d) => `  (${q(d.name)}, ${q(d.code)}, ${C}, ${C})`).join(",\n") + ";",
  "",
  "-- One administrator account per department",
  "INSERT INTO department_admins (username, password_hash, name, email, department_id, college_id) VALUES",
  DEPARTMENTS.map(
    (d) => `  (${q(d.admin)}, hash_password(${q(DEPARTMENT_ADMIN_PASSWORD)}), ${q(`${d.code} Timetable Coordinator`)}, ${q(`${d.admin}@${DATA.key}.example`)}, ${dept(d.code)}, ${C})`,
  ).join(",\n") + ";",
  "",
  "-- Faculty (college-wide pool; common-department faculty teach every department)",
  "INSERT INTO faculty (code, name, email, phone, department_id, college_id, created_by, is_active) VALUES",
  FACULTY.map(
    (f) => `  (${q(f.code)}, ${q(f.name)}, ${q(`${f.code.toLowerCase()}@${DATA.key}.example`)}, ${q(f.phone)}, ${dept(f.dept)}, ${C}, ${C}, true)`,
  ).join(",\n") + ";",
  "",
)

const windows = FACULTY.flatMap((f) => (f.availability || []).map((a) => ({ code: f.code, ...a })))
if (windows.length > 0) {
  push(
    "-- Declared availability (faculty without rows are available all week)",
    "INSERT INTO faculty_availability (faculty_id, day_of_week, start_period, end_period) VALUES",
    windows.map((w) => `  (${faculty(w.code)}, ${w.day}, ${w.start}, ${w.end})`).join(",\n") + ";",
    "",
  )
}

push(
  "-- Shared classrooms",
  "INSERT INTO classrooms (name, capacity, room_type, building, college_id, created_by) VALUES",
  ROOMS.map((r) => `  (${q(r.name)}, ${r.capacity}, ${q(r.type)}, ${q(r.building)}, ${C}, ${C})`).join(",\n") + ";",
  "",
  "-- Subjects (owned by the offering department)",
  "INSERT INTO subjects (name, code, subject_type, periods_per_week, department_id, college_id, created_by) VALUES",
  SUBJECTS.map((s) => `  (${q(s.name)}, ${q(s.code)}, ${q(s.type)}, ${s.periods}, ${dept(s.dept)}, ${C}, ${C})`).join(",\n") + ";",
  "",
  "-- Sections",
  "INSERT INTO sections (name, year_level, student_count, department_id, college_id, created_by) VALUES",
  SECTIONS.map((s) => `  (${q(s.name)}, ${s.year}, ${s.students}, ${dept(s.dept)}, ${C}, ${C})`).join(",\n") + ";",
  "",
)

const subjectFaculty = new Set<string>()
for (const s of SECTIONS) for (const [subjectCode, facultyCode] of Object.entries(s.courses)) subjectFaculty.add(`${subjectCode}|${facultyCode}`)

push(
  "-- Faculty qualified for each subject",
  "INSERT INTO subject_faculty (subject_id, faculty_id) VALUES",
  [...subjectFaculty].map((k) => {
    const [s, f] = k.split("|")
    return `  (${subject(s)}, ${faculty(f)})`
  }).join(",\n") + ";",
  "",
  "-- Section curriculum: subject + teaching faculty",
  "INSERT INTO section_subjects (section_id, subject_id, faculty_id) VALUES",
  SECTIONS.flatMap((s) => Object.entries(s.courses).map(([subjectCode, facultyCode]) => `  (${section(s.name)}, ${subject(subjectCode)}, ${faculty(facultyCode)})`)).join(",\n") + ";",
  "",
  "COMMIT;",
  "",
)

// Run from my-app/ (npm scripts do)
const target = resolve(process.cwd(), "scripts", OUTPUT)
writeFileSync(target, out.join("\n"))
console.log(`Wrote ${target}`)
